def simulate_ci(base_tokens, head_tokens):
    H_base, H_head = shannon_entropy(base_tokens), shannon_entropy(head_tokens)
    delta = H_head - H_base
    Dkl = kl_div(head_tokens, base_tokens)
    print(f"Base entropy: {H_base:.2f}, Head entropy: {H_head:.2f}, ΔH={delta:.2f}, KL={Dkl:.2f}")
    if delta > 1.0:
        return "BLOCK ❌  –  High complexity increase"
    elif Dkl > 0.2:
        return "WARN ⚠️  –  Significant structural change"
    else:
        return "PASS ✅  –  Within limits"

