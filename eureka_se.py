import re, math, gzip, json
from collections import Counter
import os

# --- Tokenization & Entropy ---
TOKEN_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*|==|!=|<=|>=|->|:=|[-+*/%<>]=?|[:();,\.]|\d+")

def tokenize_code(code: str):
    return TOKEN_RE.findall(code)

def shannon_entropy(tokens):
    if not tokens: return 0.0
    n, counts = len(tokens), Counter(tokens)
    return -sum((c/n)*math.log2(c/n) for c in counts.values())

# --- Kolmogorov Complexity Approximation ---
def kc_ratio(code: str):
    if not code: return 0.0
    orig = len(code.encode())
    comp = len(gzip.compress(code.encode()))
    return comp / orig

# --- Mutual Information & KL Divergence ---
def mutual_info(a, b):
    if not a or not b: return 0.0
    ca, cb = Counter(a), Counter(b)
    na, nb = len(a), len(b)
    I = 0.0
    for k in set(ca)|set(cb):
        pa, pb = ca.get(k,0)/na, cb.get(k,0)/nb
        p_ab = (pa+pb)/2
        if p_ab>0:
            I += p_ab*math.log2((p_ab/(pa*pb+1e-12))+1e-12)
    return I

def kl_div(p, q):
    cp, cq = Counter(p), Counter(q)
    tp, tq = len(p), len(q)
    D = 0.0
    for k in set(cp)|set(cq):
        pk, qk = cp.get(k,0)/tp if tp else 0, cq.get(k,0)/tq if tq else 0
        pk, qk = max(pk,1e-12), max(qk,1e-12)
        D += pk*math.log2(pk/qk)
    return D

